#!/usr/bin/env python3
"""
Generate the manuscript's numeric table bodies from the committed CSVs.

WHY THIS EXISTS
---------------
Every table in main.tex was hand-typed, and the same values were independently
re-typed across main.tex, both letters, TIER1_FINDINGS.md, PAPER_NUMBERS.md,
REPRODUCE.md, README.md and ARCHITECTURE.md. Of 130 findings in audit rounds 17-27,
26 were the same defect: a fix landed in one document and went stale in its
counterpart. check_numbers.py can only DETECT that drift after the fact. This makes
the table half of it impossible, by giving the numbers exactly one source.

Writes two files, each a complete `\\begin{tabular}...\\end{tabular}` block:

    paper/tab_reportcard.tex   <- Table 2, the near-duplicate leakage report card
    paper/tab_roster.tex       <- Table 3, the nine-model roster on ensembl

Captions, labels, \\resizebox and font-size wrappers stay in main.tex. Only the
numeric body moves, so nothing about the layout changes.

PROVENANCE, INCLUDING THE AWKWARD PART
--------------------------------------
The report card is NOT a single CSV. Its "Acc. lost" column mixes two conventions and
this is deliberate in the manuscript, so the generator reproduces it explicitly rather
than silently:

  * the two LEAKY rows use the reconciled convention -- original RF accuracy from
    chromosome_holdout.csv (split=original, model=RF, k=6) minus the five-re-split-seed
    mean corrected accuracy from splitter_validation.csv. This is the .predict()/argmax
    + 5-seed-mean convention the paper fixes in its header note, and it is why these
    rows read +0.118 / +0.165 rather than leakage_report_card.csv's single-seed
    acc_drop_seed0 of 0.108 / 0.164.
  * the clean and borderline rows use leakage_report_card.csv's acc_drop_seed0, which
    for those datasets IS the reported figure.
  * the three-class row uses acc_drop_corrected.

The "Reorders under chrom.-holdout?" column is derived by comparing RF rank between
split=original and split=chromosome_holdout in chromosome_holdout.csv, and is n/a for
every dataset that control was not run on.

If any of those sources moves, the table moves with it. That is the point.

USAGE
    ./venv/bin/python -m audit.pipeline.emit_tables          # writes both files
    ./venv/bin/python -m audit.pipeline.emit_tables --check  # verify, write nothing
"""
from __future__ import annotations
import argparse
import os
import sys

import pandas as pd
from decimal import Decimal, ROUND_HALF_UP

HERE = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
R = os.path.join(HERE, "results")
PAPER = os.path.join(HERE, "paper")

GENERATED = ("% GENERATED by audit/pipeline/emit_tables.py -- do not edit by hand.\n"
             "% Edit the source CSV and re-run, or the next build will overwrite you.\n")

# Row order as the manuscript presents it: leaky first, then borderline, then clean by
# descending leak, with the three-class set below a midrule.
REPORTCARD_ORDER = [
    "human_nontata_promoters",
    "human_enhancers_ensembl",
    "demo_coding_vs_intergenomic_seqs",
    "human_ocr_ensembl",
    "demo_human_or_worm",
    "drosophila_enhancers_stark",
    "human_enhancers_cohn",
]
THREE_CLASS = "human_ensembl_regulatory (3-class)"

# CSV model id -> the name the manuscript prints
ROSTER_NAMES = {"RF": "RandomForest", "LR": "LogisticReg.", "HGB": "HistGB"}


def tex_name(s: str) -> str:
    return s.replace("_", r"\_")


def num(x, places=3, signed=False):
    """Round HALF-UP, not with binary float formatting.

    This is not pedantry. Two of the manuscript's committed values are exact half-ties
    at the printed precision -- ExtraTrees' raw graded gap (0.2095) and the ensembl
    accuracy lost (0.8596 - 0.6951 = 0.1645) -- and both land a digit BELOW the
    published figure under f-string formatting, because neither is exactly representable
    in binary and both fall marginally short of the tie. Formatting them with `%.3f`
    silently produces 0.209 and 0.164 against the published 0.210 and 0.165, which would
    have looked like the generator finding two manuscript errors rather than introducing
    two of its own.
    """
    if x is None or (isinstance(x, float) and pd.isna(x)):
        return "--"
    q = Decimal(str(x)).quantize(Decimal(1).scaleb(-places), rounding=ROUND_HALF_UP)
    s = f"{q:+f}" if signed else f"{q:f}"
    return s


def build_reportcard() -> str:
    card = pd.read_csv(os.path.join(R, "leakage_report_card.csv")).set_index("dataset")
    chrom = pd.read_csv(os.path.join(R, "chromosome_holdout.csv"))
    val = pd.read_csv(os.path.join(R, "splitter_validation.csv")).set_index("dataset")

    rf6 = chrom[(chrom.model == "RF") & (chrom.k == 6)]
    orig = rf6[rf6.split == "original"].set_index("dataset")
    held = rf6[rf6.split == "chromosome_holdout"].set_index("dataset")

    def acc_lost(d):
        """Reconciled 5-seed drop for the leaky pair; single-seed elsewhere."""
        if d in val.index and d in orig.index:
            return (Decimal(str(orig.loc[d, "acc"]))
                    - Decimal(str(val.loc[d, "corrected_acc_mean"])))
        return float(card.loc[d, "acc_drop_seed0"])

    def reorders(d):
        if d not in orig.index or d not in held.index:
            return "n/a"
        r0, r1 = int(orig.loc[d, "rf_rank"]), int(held.loc[d, "rf_rank"])
        if r0 == r1:
            return f"no (RF stays rank~{r1})"
        return rf"yes (RF $\to$ rank~{r1})"

    lines = [r"\begin{tabular}{@{}lrrrlrll@{}}", r"\toprule",
             (r"Dataset & $n$ (full) & leak@0.7 (Jac) & leak@0.7 (con) & Verdict & "
              r"Acc.\ lost & RF rank & Reorders under chrom.-holdout?\\"),
             r"\midrule"]

    for d in REPORTCARD_ORDER:
        row = card.loc[d]
        verdict = str(row["verdict"])
        # Three tiers, not two. `leaky-but-correction-unsafe` is what certify.py emits
        # when a LEAKY dataset's largest-cluster cohesion falls below 0.5: its
        # components are single-linkage chains rather than near-duplicate sets, so
        # whole-cluster re-splitting quarantines related but non-duplicate sequences
        # and removes genuine signal along with the leakage. The verdict is still
        # LEAKY -- the corrected delta is what cannot be taken at face value.
        vtex = {
            "LEAKY": r"\textbf{LEAKY}",
            "leaky-but-correction-unsafe": r"\textbf{LEAKY}$^{\ddagger}$",
        }.get(verdict, verdict)
        con = num(row["leak_containment_0p7"])
        if verdict == "borderline":
            vtex = vtex + r"$^{\dagger}$"
            con = r"\textbf{" + con + "}"        # the value the length-blind metric misses
        rank = str(row["rf_rank_orig_to_corr"]).replace("->", r"\!\to\!")
        lines.append(
            f"{tex_name(d)} & {int(row['n_full']):,} & {num(row['leak_at_0p7'])} & {con} & "
            f"{vtex} & ${num(acc_lost(d), signed=True)}$ & "
            f"${rank}$ & {reorders(d)}\\\\".replace(",", "{,}"))

    lines.append(r"\midrule")
    tc = card.loc[THREE_CLASS]
    lines.append(
        f"{tex_name(THREE_CLASS)} & {int(tc['n_full']):,} & {num(tc['leak_at_0p7'])} & -- & "
        f"{tc['verdict']} & ${num(tc['acc_drop_corrected'], signed=True)}$ & n/a & n/a\\\\"
        .replace(",", "{,}"))
    lines += [r"\botrule", r"\end{tabular}"]
    return GENERATED + "\n".join(lines) + "\n"


def build_roster() -> str:
    rank = pd.read_csv(os.path.join(R, "roster_rankings.csv"))
    gaps = pd.read_csv(os.path.join(R, "graded_gap_corrected.csv"))
    D = "human_enhancers_ensembl"
    rank = rank[rank.dataset == D].set_index("model")
    gaps = gaps[gaps.dataset == D].set_index("model")

    lines = [r"\begin{tabular}{@{}lrrrrrl@{}}", r"\toprule",
             (r"Model & Gap$_{\text{bal}}$ & Gap$_{\text{raw}}$ & As-shipped & Corrected & "
              r"Drop & Rank\\"),
             r"\midrule"]

    for m in rank.sort_values("rank_orig").index:
        r = rank.loc[m]
        bal = num(gaps.loc[m, "graded_gap_balanced"])
        raw = num(gaps.loc[m, "graded_gap_raw"])
        shipped = num(r["acc_orig"], places=4)
        corr = num(r["acc_corr"], places=4)
        if int(r["rank_orig"]) == 1:
            shipped = r"\textbf{" + shipped + "}"
        if int(r["rank_corr"]) == 1:
            corr = r"\textbf{" + corr + "}"
        star = "^{*}" if bool(r["drop_excl0"]) else ""
        lines.append(
            f"{ROSTER_NAMES.get(m, m)} & \\textbf{{{bal}}} & ${raw}$ & {shipped} & {corr} & "
            f"${num(r['drop'])}{star}$ & "
            f"${int(r['rank_orig'])}\\!\\to\\!{int(r['rank_corr'])}$\\\\")

    lines += [r"\botrule", r"\end{tabular}"]
    return GENERATED + "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="regenerate in memory and fail if the committed files differ")
    a = ap.parse_args()

    targets = {
        os.path.join(PAPER, "tab_reportcard.tex"): build_reportcard(),
        os.path.join(PAPER, "tab_roster.tex"): build_roster(),
    }
    stale = []
    for path, body in targets.items():
        if a.check:
            cur = open(path).read() if os.path.exists(path) else None
            if cur != body:
                stale.append(os.path.basename(path))
            continue
        with open(path, "w") as fh:
            fh.write(body)
        print(f"wrote {os.path.relpath(path, HERE)} ({len(body.splitlines())} lines)")

    if a.check:
        if stale:
            print("STALE (regenerate with `python -m audit.pipeline.emit_tables`): "
                  + ", ".join(stale))
            sys.exit(1)
        print("tables are current")


if __name__ == "__main__":
    main()
